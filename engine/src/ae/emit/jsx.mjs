// IR -> ExtendScript that builds the comp inside After Effects.
//
// ExtendScript is ES3: no let/const, no arrow functions, no JSON, no Array
// helpers. Everything emitted here stays inside that dialect, and the data
// travels as a literal rather than through eval() of a file.
//
// Two decisions worth stating up front:
//
// 1. POSITION DIMENSIONS ARE SEPARATED. CSS translateX and translateY are
//    independent properties with independent timing functions; AE's unified
//    Position is a single SPATIAL property with one temporal ease and a motion
//    path whose spatial tangents bend straight moves into curves. Separating
//    the dimensions makes the AE model match the CSS model exactly, so an ease
//    that differs per axis survives instead of being averaged away.
//
// 2. THE SCRIPT VERIFIES ITSELF. Before building anything it creates a throwaway
//    comp, parents one layer to another with known values, and reads back where
//    a point actually lands. If After Effects does not agree with the coordinate
//    model in src/analyze/layers.mjs, the import stops and says so rather than
//    producing a comp that is subtly wrong everywhere.
import { RUNTIME } from './runtime.mjs';
import { sliderName } from '../ir/clippath.mjs';
import { parseColor, primaryFontFamily } from '../analyze/css.mjs';

const HEADER = `// Generated by Canvas Render. Do not edit by hand; convert the scene again instead.
// Builds an After Effects composition from a captured design: run it from
// File > Scripts > Run Script File, or import it from the Canvas Render panel.
#target aftereffects
`;

const ESCAPES = { '\\': '\\\\', '"': '\\"', '\r': '\\r', '\n': '\\n', '\t': '\\t' };

function esc(str) {
  let out = '';
  const s = String(str);
  for (let i = 0; i < s.length; i += 1) {
    const ch = s[i];
    const code = s.charCodeAt(i);
    if (ESCAPES[ch]) out += ESCAPES[ch];
    else if (code < 0x20 || code > 0x7e) out += `\\u${code.toString(16).padStart(4, '0')}`;
    else out += ch;
  }
  return out;
}

function num(n) {
  if (!Number.isFinite(n)) return '0';
  const r = Math.round(n * 1e6) / 1e6;
  return Object.is(r, -0) ? '0' : String(r);
}

/** Serialise a JS value as an ExtendScript literal (ES3-safe: no JSON). */
export function literal(value, indent = 0) {
  const pad = '  '.repeat(indent);
  const padIn = '  '.repeat(indent + 1);
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return num(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'string') return `"${esc(value)}"`;
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    const flat = value.every((v) => typeof v === 'number' || typeof v === 'boolean' || v === null);
    if (flat) return `[${value.map((v) => literal(v)).join(', ')}]`;
    return `[\n${value.map((v) => padIn + literal(v, indent + 1)).join(',\n')}\n${pad}]`;
  }
  const entries = Object.entries(value).filter(([, v]) => v !== undefined);
  if (!entries.length) return '{}';
  const body = entries
    .map(([k, v]) => `${padIn}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : `"${esc(k)}"`}: ${literal(v, indent + 1)}`)
    .join(',\n');
  return `{\n${body}\n${pad}}`;
}

/** Convert an IR track into the compact ExtendScript form. */
export function encodeTrack(track, transform = (v) => v) {
  if (!track) return null;
  if (track.keys === undefined) {
    return { s: Array.isArray(track.static) ? track.static.map(transform) : transform(track.static) };
  }
  const dims = Array.isArray(track.keys[0].v) ? track.keys[0].v.length : 1;
  const pad = (list) => {
    const out = list.map((e) => [e.speed, e.influence]);
    while (out.length < dims) out.push(out[out.length - 1] || [0, 16.666667]);
    return out;
  };
  return {
    k: track.keys.map((key) => [
      key.t,
      Array.isArray(key.v) ? key.v.map(transform) : transform(key.v),
      key.hold ? 1 : 0,
      pad(Array.isArray(key.inEase) ? key.inEase : [key.inEase]),
      pad(Array.isArray(key.outEase) ? key.outEase : [key.outEase]),
    ]),
  };
}

/** One 1-D track per dimension, for AE's separated Position properties. */
export function splitTrackDimensions(track) {
  if (!track) return null;
  if (track.keys === undefined) return track.static.map((v) => ({ s: v }));
  const dims = track.keys[0].v.length;
  const out = [];
  for (let d = 0; d < dims; d += 1) {
    out.push({
      k: track.keys.map((key) => [
        key.t, key.v[d], key.hold ? 1 : 0,
        [[key.inEase[d].speed, key.inEase[d].influence]],
        [[key.outEase[d].speed, key.outEase[d].influence]],
      ]),
    });
  }
  return out;
}

/**
 * The two points After Effects wants for a Gradient Ramp, in LAYER space.
 *
 * CSS measures a linear gradient's angle clockwise from "to top", and runs the
 * gradient line through the box centre with a length of |W.sin| + |H.cos| so
 * that both far corners are reached.
 *
 * A radial gradient is centred at its `at` position (default centre) and sized
 * by its explicit radii or extent keyword (default farthest-corner). AE's ramp
 * is a circle, so an ellipse gets the geometric mean of its two radii, which
 * keeps the falloff's area right; `elliptical` says when that happened.
 */
export function rampGeometry(g, size, css = '') {
  const [w, h] = size;
  if (g.kind === 'radial' || g.kind === 'conic') {
    const r = radialShape(css, w, h);
    return { start: [r.cx, r.cy], end: [r.cx + r.radius, r.cy], elliptical: r.elliptical };
  }
  const cx = w / 2;
  const cy = h / 2;
  const theta = ((g.angle || 180) * Math.PI) / 180;
  // Screen coordinates are y-down, so "to top" is -y.
  const dx = Math.sin(theta);
  const dy = -Math.cos(theta);
  const length = Math.abs(w * Math.sin(theta)) + Math.abs(h * Math.cos(theta));
  return {
    start: [cx - (dx * length) / 2, cy - (dy * length) / 2],
    end: [cx + (dx * length) / 2, cy + (dy * length) / 2],
  };
}

/** Centre and radius of a CSS radial-gradient's ending shape in a w x h box. */
export function radialShape(css, w, h) {
  const open = (css || '').indexOf('radial-gradient(');
  let first = '';
  if (open !== -1) {
    // The first top-level argument, which is the shape/size/position prelude
    // when there is one and otherwise the first colour stop.
    let depth = 0;
    for (let i = open + 'radial-gradient('.length; i < css.length; i += 1) {
      const ch = css[i];
      if (ch === '(') depth += 1;
      else if (ch === ')') { if (depth === 0) break; depth -= 1; }
      else if (ch === ',' && depth === 0) break;
      first += ch;
    }
  }
  first = first.trim();
  const isPrelude = /(^|\s)(at|circle|ellipse|closest-side|closest-corner|farthest-side|farthest-corner)(\s|$)/.test(first)
    || /^[-\d.]+(px|%|em|rem)?(\s+[-\d.]+(px|%|em|rem)?)?$/.test(first);
  const head = isPrelude ? first : '';
  const [shapePart, atPart] = /^at\s/.test(head) ? ['', head.slice(3)] : head.split(/\s+at\s+/);
  const len = (tok, ref) => (tok.endsWith('%') ? (parseFloat(tok) / 100) * ref : parseFloat(tok));
  const KEY_X = { left: 0, center: 0.5, right: 1 };
  const KEY_Y = { top: 0, center: 0.5, bottom: 1 };
  let cx = w / 2;
  let cy = h / 2;
  if (atPart) {
    const toks = atPart.trim().split(/\s+/);
    // Keywords can come in either order ("top left"); lengths are x then y.
    let x = null;
    let y = null;
    for (const tok of toks) {
      if (tok in KEY_Y && tok !== 'center' && y === null) y = KEY_Y[tok] * h;
      else if (tok in KEY_X && tok !== 'center' && x === null) x = KEY_X[tok] * w;
      else if (tok === 'center') { if (x === null) x = w / 2; else if (y === null) y = h / 2; }
      else if (x === null) x = len(tok, w);
      else if (y === null) y = len(tok, h);
    }
    cx = x ?? w / 2;
    cy = y ?? h / 2;
  }
  const sideX = [cx, w - cx];
  const sideY = [cy, h - cy];
  const toks = (shapePart || '').trim().split(/\s+/).filter(Boolean);
  const circle = toks.includes('circle');
  const lengths = toks.filter((t) => /^[-\d.]/.test(t));
  const extent = toks.find((t) => /(closest|farthest)-(side|corner)/.test(t)) || 'farthest-corner';
  let rx;
  let ry;
  if (lengths.length >= 2) { rx = len(lengths[0], w); ry = len(lengths[1], h); }
  else if (lengths.length === 1) { rx = len(lengths[0], w); ry = rx; }
  else {
    const near = extent.startsWith('closest');
    const pick = (a) => (near ? Math.min(...a) : Math.max(...a));
    const sx = pick(sideX);
    const sy = pick(sideY);
    if (circle) {
      const r = extent.endsWith('side') ? pick([...sideX, ...sideY]) : Math.hypot(sx, sy);
      rx = r; ry = r;
    } else if (extent.endsWith('side')) { rx = sx; ry = sy; }
    else { rx = sx * Math.SQRT2; ry = sy * Math.SQRT2; }
  }
  const radius = Math.sqrt(Math.max(rx, 0) * Math.max(ry, 0)) || Math.max(rx, ry) || 1;
  return { cx, cy, rx, ry, radius, elliptical: Math.abs(rx - ry) > 0.1 * Math.max(rx, ry) };
}

const AE_JUSTIFY = { left: 7413, center: 7415, right: 7414, start: 7413, end: 7414, justify: 7416 };

export function buildPayload(ir, options = {}) {
  const separatePosition = options.separatePosition !== false;
  // Compositions are emitted in dependency order -- a perspective precomp must
  // exist before the comp that places it -- and buildIR already unshifts them.
  const comps = ir.comps.map((comp) => ({
    id: comp.id,
    name: comp.name,
    width: comp.width,
    height: comp.height,
    fps: comp.fps,
    duration: comp.duration,
    bg: comp.backgroundColor.rgb,
    bgAlpha: comp.backgroundColor.a,
    camera: comp.camera
      ? { name: `Perspective (${comp.camera.name})`, zoom: comp.camera.distance, point: comp.camera.point }
      : null,
    layers: comp.layers.map((layer) => encodeLayer(layer, separatePosition)),
  }));

  return {
    separatePosition,
    rootCompId: ir.rootCompId,
    // Footage is imported once and shared: a sprite used by ten layers becomes
    // one project item, as it would if a person imported it by hand.
    assets: (ir.assets || []).map((a) => ({
      id: a.id,
      file: a.file || null,
      relative: a.relative || null,
      width: a.width,
      height: a.height,
      sequence: a.kind === 'sequence',
      frames: a.frames || 1,
    })),
    comps,
  };
}

function encodeLayer(layer, separatePosition) {
  const t = layer.transform;
  const encoded = {
    id: layer.id,
    name: layer.name,
    parentId: layer.parentId,
    kind: layer.kind,
    compId: layer.compId || null,
    inPoint: layer.inPoint,
    outPoint: layer.outPoint,
    loop: layer.loop ? true : false,
    blendMode: layer.blendMode && layer.blendMode !== 'NORMAL' ? layer.blendMode : null,
    comment: `d2ae tier ${layer.tier} | ${layer.role}`,
    transform: {
      threeD: layer.threeD,
      anchorPoint: encodeTrack(t.anchorPoint),
      position: encodeTrack(t.position),
      positionSeparated: separatePosition ? splitTrackDimensions(t.position) : null,
      scale: encodeTrack(t.scale),
      opacity: encodeTrack(t.opacity),
      rotation: t.rotation ? encodeTrack(t.rotation) : null,
      rotationXYZ: t.orientation ? splitTrackDimensions(t.orientation) : null,
    },
    effects: encodeEffects(layer),
    mask: layer.mask || null,
    image: layer.image || null,

  };
  if (layer.clip) encoded.clip = encodeClip(layer.clip);
  if (layer.clipBy) encoded.clipBy = encodeClip(layer.clipBy);
  if (layer.kind === 'shape') encoded.shape = encodeShape(layer.shape);
  if (layer.kind === 'text') encoded.text = encodeText(layer);
  if (layer.stagger) encoded.stagger = encodeStagger(layer);
  if (layer.kind === 'path') encoded.path = encodePath(layer);
  return encoded;
}

/**
 * A clip-path for the runtime. `values` holds each slider's track (when this
 * layer carries the sliders) and `names` the slider names, in path order.
 * A static clip carries constants instead, so the mask needs no sliders.
 */
function encodeClip(clip) {
  const out = {
    role: clip.role,
    shape: clip.shape,
    clipper: clip.clipper,
    animated: clip.animated,
    off: clip.off,
    scale: clip.scale,
    names: clip.keys.map(sliderName),
  };
  out.statics = clip.statics;
  if (clip.tracks && clip.animated) out.tracks = clip.keys.map((k) => encodeTrack(clip.tracks[k]));
  if (clip.path && clip.role === 'self') out.path = clip.path;
  return out;
}

export function emitJsx(ir, options = {}) {
  const data = buildPayload(ir, options);
  return `${HEADER}
${RUNTIME}

var D2AE_DATA = ${literal(data, 0)};

(function () {
  app.beginUndoGroup("Import from Canvas Render");
  try {
    var comp = D2AE.build(D2AE_DATA);
    var summary = "Imported " + comp.name + ".";
    if (D2AE.log.length) summary += "\\n\\nNotes:\\n" + D2AE.log.join("\\n");
    D2AE.report(summary);
  } catch (err) {
    D2AE.report("Import failed:\\n" + err.toString());
  } finally {
    app.endUndoGroup();
  }
})();
`;
}

function encodeShape(shape) {
  if (!shape) return null;
  const out = {
    size: encodeTrack(shape.size),
    roundness: shape.roundness ? encodeTrack(shape.roundness) : null,
    fill: { color: encodeTrack(shape.fill.color), opacity: encodeTrack(shape.fill.opacity) },
    stroke: shape.stroke
      ? { width: shape.stroke.width, color: shape.stroke.color.rgb, alpha: shape.stroke.color.a }
      : null,
    gradient: null,
  };
  if (shape.gradient && shape.gradient.linear && shape.gradient.linear.stops.length >= 2) {
    // Gradients import as a real After Effects Gradient Ramp effect.
    //
    // The obvious route -- a shape-layer Gradient Fill -- is a dead end: its
    // "ADBE Vector Grad Colors" property reports PropertyValueType.NO_VALUE and
    // refuses both get and set, so the stops cannot be written from a script and
    // the fill would import as AE's default black-to-white.
    //
    // ADBE Ramp has none of that problem. It is fully scriptable, and applied to
    // a shape layer it RESPECTS THE SHAPE'S ALPHA -- the gradient fills the
    // rounded rectangle and leaves everything around it alone -- so one layer is
    // enough and no track matte is needed.
    const size = shape.size.keys ? shape.size.keys[0].v : shape.size.static;
    const g = shape.gradient.linear;
    const stops = g.stops;
    const first = stops[0];
    const last = stops[stops.length - 1];

    out.ramp = {
      shape: g.kind === 'radial' || g.kind === 'conic' ? 2 : 1,
      ...rampGeometry(g, size, shape.gradient.css),
      startColor: first.color.rgb,
      endColor: last.color.rgb,
    };

    // Ramp discards the alpha channel of its colours (measured: a colour-to-
    // transparent ramp renders fully opaque), so an alpha falloff has to ride on
    // the layer's own opacity. A constant alpha is exact; a varying one is
    // averaged and reported.
    const alphas = stops.map((stop) => stop.color.a);
    const alphaSpread = Math.max(...alphas) - Math.min(...alphas);
    const meanAlpha = alphas.reduce((a, b) => a + b, 0) / alphas.length;
    out.ramp.opacity = Math.max(0, Math.min(100, meanAlpha * 100));
    out.ramp.alphaVaries = alphaSpread > 0.02;
    out.ramp.stopCount = stops.length;
    // Keep a flat fill underneath as the colour the layer falls back to if the
    // effect cannot be applied at all.
    out.fill = { color: { s: first.color.rgb }, opacity: { s: out.ramp.opacity } };
  }
  return out;
}

function encodeText(layer) {
  const t = layer.text;
  return {
    value: t.value,
    font: t.font,
    weight: t.weight,
    italic: t.italic,
    size: t.size.keys ? t.size.keys[0].v : t.size.static,
    color: t.color.keys ? t.color.keys[0].v : t.color.static,
    tracking: Math.round(t.tracking),
    // Letters the browser laid out as separate boxes (a staggered run is always
    // one box per letter) are never kerned against each other, and neither is
    // font-kerning: none. AE kerns by font metrics unless told otherwise.
    kern: layer.stagger || t.kerning === 'none' ? 'none' : 'metric',
    leading: t.leading,
    justification: AE_JUSTIFY[t.align] ?? AE_JUSTIFY.left,
  };
}

/**
 * A collapsed run of staggered spans, as one text animator.
 *
 * The animator holds the state the run animates FROM; each member gets a Range
 * Selector over its own characters whose Amount blends that state away on its
 * own schedule. Position is an offset, opacity and scale are absolute values
 * the selected characters take -- which is why the detector resolves them
 * differently before they get here.
 */
function encodeStagger(layer) {
  const st = layer.stagger;
  const base = st.members[0].style || {};
  const rgb = (css) => { const c = parseColor(css); return c ? c.rgb : null; };
  return {
    from: st.from,
    members: st.members.map((m) => {
      const style = m.style || {};
      // Only what actually differs from the layer's own styling: everything
      // else is already set on the text document and a redundant character
      // override would just be another thing to unpick by hand.
      const restyle = {};
      if (style.color && style.color !== base.color) restyle.color = rgb(style.color);
      if (style.italic !== base.italic || style.weight !== base.weight) {
        restyle.italic = style.italic;
        restyle.weight = style.weight;
        // The PRIMARY family, not the CSS stack. Handing After Effects
        // '"InstrumentSerif",Georgia,serif' as a font name is accepted without
        // complaint and then rendered as a fallback face, which looks like the
        // italic simply failing to apply.
        restyle.font = primaryFontFamily(style.family);
      }
      return {
        text: m.text,
        charStart: m.charStart,
        charEnd: m.charEnd,
        amount: encodeTrack(m.amount),
        restyle: Object.keys(restyle).length ? restyle : null,
      };
    }),
  };
}

function encodePath(layer) {
  const p = layer.path;
  const geometry = pathToShape(p);
  const out = {
    vertices: geometry.vertices,
    inTangents: geometry.inTangents,
    outTangents: geometry.outTangents,
    closed: geometry.closed,
    strokeWidth: p.strokeWidth,
    strokeColor: encodeTrack(p.strokeColor),
    fill: p.fillColor && p.fillColor.a > 0 ? { c: p.fillColor.rgb, a: p.fillColor.a } : null,
    lineCap: p.lineCap === 'round' ? 2 : (p.lineCap === 'square' ? 3 : 1),
    trim: null,
    morph: null,
  };
  // An animated `d`: linear keys on the Path property, one per morph key.
  if (p.morph && p.morph.keys && p.morph.keys.length > 1) {
    out.morph = {
      t: p.morph.keys.map((k) => k.t),
      v: p.morph.keys.map((k) => k.vertices),
      i: p.morph.straight ? null : p.morph.keys.map((k) => k.inTangents),
      o: p.morph.straight ? null : p.morph.keys.map((k) => k.outTangents),
      closed: p.morph.closed,
    };
  }
  // stroke-dashoffset animating against a dasharray equal to the path length is
  // the canonical CSS draw-on. AE says the same thing with Trim Paths, which is
  // both idiomatic and directly editable -- so we translate the idiom, not just
  // the numbers.
  if (p.dashOffset && p.dashOffset.keys && p.totalLength > 0) {
    const toPercent = (v) => Math.max(0, Math.min(100, (1 - v / p.totalLength) * 100));
    out.trim = {
      end: {
        k: p.dashOffset.keys.map((key) => [
          key.t,
          toPercent(key.v),
          key.hold ? 1 : 0,
          [[-(key.inEase.speed / p.totalLength) * 100, key.inEase.influence]],
          [[-(key.outEase.speed / p.totalLength) * 100, key.outEase.influence]],
        ]),
      },
      start: null,
    };
  }
  return out;
}

/**
 * Convert an SVG path `d` into AE Shape vertex/tangent arrays.
 * Handles M/L/H/V/C/S/Q/T/Z, absolute and relative. Quadratics are elevated to
 * cubics exactly. Arcs are approximated by their chord, because AE shapes have
 * no arc primitive -- the caller reports that rather than hiding it.
 */
export function pathToShape(p) {
  const empty = { vertices: [], inTangents: [], outTangents: [], closed: false, approximated: [] };
  if (!p) return empty;
  if (!p.d) return geomToShape(p) || empty;
  const tokens = p.d.match(/[MmLlHhVvCcSsQqTtAaZz]|[-+]?[0-9]*\.?[0-9]+(?:[eE][-+]?[0-9]+)?/g);
  if (!tokens) return empty;

  const vertices = [];
  const inT = [];
  const outT = [];
  const approximated = [];
  let closed = false;
  let x = 0; let y = 0;
  let startX = 0; let startY = 0;
  let lastControl = null;
  let cmd = null;
  let i = 0;

  const push = (px, py) => { vertices.push([px, py]); inT.push([0, 0]); outT.push([0, 0]); };
  const nextNum = () => { i += 1; return Number(tokens[i]); };

  while (i < tokens.length) {
    const tok = tokens[i];
    if (/[A-Za-z]/.test(tok)) cmd = tok;
    else i -= 1;
    if (!cmd) { i += 1; continue; }
    const rel = cmd === cmd.toLowerCase();
    switch (cmd.toUpperCase()) {
      case 'M': {
        const nx = nextNum(); const ny = nextNum();
        x = rel ? x + nx : nx; y = rel ? y + ny : ny;
        startX = x; startY = y;
        push(x, y);
        cmd = rel ? 'l' : 'L';
        lastControl = null;
        break;
      }
      case 'L': {
        const nx = nextNum(); const ny = nextNum();
        x = rel ? x + nx : nx; y = rel ? y + ny : ny;
        push(x, y); lastControl = null;
        break;
      }
      case 'H': { const nx = nextNum(); x = rel ? x + nx : nx; push(x, y); lastControl = null; break; }
      case 'V': { const ny = nextNum(); y = rel ? y + ny : ny; push(x, y); lastControl = null; break; }
      case 'C': case 'S': {
        let c1x; let c1y;
        if (cmd.toUpperCase() === 'C') {
          c1x = nextNum(); c1y = nextNum();
          if (rel) { c1x += x; c1y += y; }
        } else {
          c1x = lastControl ? 2 * x - lastControl[0] : x;
          c1y = lastControl ? 2 * y - lastControl[1] : y;
        }
        let c2x = nextNum(); let c2y = nextNum();
        let ex = nextNum(); let ey = nextNum();
        if (rel) { c2x += x; c2y += y; ex += x; ey += y; }
        outT[vertices.length - 1] = [c1x - x, c1y - y];
        push(ex, ey);
        inT[vertices.length - 1] = [c2x - ex, c2y - ey];
        lastControl = [c2x, c2y];
        x = ex; y = ey;
        break;
      }
      case 'Q': case 'T': {
        let qx; let qy;
        if (cmd.toUpperCase() === 'Q') {
          qx = nextNum(); qy = nextNum();
          if (rel) { qx += x; qy += y; }
        } else {
          qx = lastControl ? 2 * x - lastControl[0] : x;
          qy = lastControl ? 2 * y - lastControl[1] : y;
        }
        let ex = nextNum(); let ey = nextNum();
        if (rel) { ex += x; ey += y; }
        // Exact degree elevation: a quadratic IS a cubic with these controls.
        outT[vertices.length - 1] = [(2 / 3) * (qx - x), (2 / 3) * (qy - y)];
        push(ex, ey);
        inT[vertices.length - 1] = [(2 / 3) * (qx - ex), (2 / 3) * (qy - ey)];
        lastControl = [qx, qy];
        x = ex; y = ey;
        break;
      }
      case 'A': {
        nextNum(); nextNum(); nextNum(); nextNum(); nextNum();
        let ex = nextNum(); let ey = nextNum();
        if (rel) { ex += x; ey += y; }
        approximated.push('elliptical arc flattened to a straight segment');
        push(ex, ey);
        x = ex; y = ey; lastControl = null;
        break;
      }
      case 'Z': { closed = true; x = startX; y = startY; break; }
      default: break;
    }
    i += 1;
  }
  return { vertices, inTangents: inT, outTangents: outT, closed, approximated };
}

const KAPPA = 0.5522847498307936;

function geomToShape(p) {
  if (!p || !p.geom) return null;
  const g = p.geom;
  const plain = (v, isClosed) => ({
    vertices: v, inTangents: v.map(() => [0, 0]), outTangents: v.map(() => [0, 0]),
    closed: isClosed, approximated: [],
  });
  if (p.tag === 'rect') {
    return plain([[g.x, g.y], [g.x + g.width, g.y], [g.x + g.width, g.y + g.height], [g.x, g.y + g.height]], true);
  }
  if (p.tag === 'line') return plain([[g.x1, g.y1], [g.x2, g.y2]], false);
  if (p.tag === 'polygon' || p.tag === 'polyline') {
    const nums = String(g.points || '').trim().split(/[\s,]+/).map(Number).filter(Number.isFinite);
    const v = [];
    for (let k = 0; k + 1 < nums.length; k += 2) v.push([nums[k], nums[k + 1]]);
    return plain(v, p.tag === 'polygon');
  }
  if (p.tag === 'circle' || p.tag === 'ellipse') {
    const rx = p.tag === 'circle' ? g.r : g.rx;
    const ry = p.tag === 'circle' ? g.r : g.ry;
    return {
      vertices: [[g.cx, g.cy - ry], [g.cx + rx, g.cy], [g.cx, g.cy + ry], [g.cx - rx, g.cy]],
      inTangents: [[-rx * KAPPA, 0], [0, -ry * KAPPA], [rx * KAPPA, 0], [0, ry * KAPPA]],
      outTangents: [[rx * KAPPA, 0], [0, ry * KAPPA], [-rx * KAPPA, 0], [0, -ry * KAPPA]],
      closed: true,
      approximated: [],
    };
  }
  return null;
}

function encodeEffects(layer) {
  const out = [];
  // Tiling comes from the background layer itself rather than the effect list,
  // because it is derived geometry, not a CSS filter.
  if (layer.tile) out.push({ type: 'tile', params: layer.tile });
  for (const fx of layer.effects || []) {
    if (fx.type === 'gaussianBlur') {
      out.push({ type: 'gaussianBlur', params: { blurriness: encodeTrack(fx.params.blurriness) } });
    } else if (fx.type === 'brightness') {
      // CSS brightness is a multiplier around 1; AE's Brightness is an additive
      // offset. Map the multiplier onto the offset that matches at mid-grey --
      // the closest single-parameter equivalent, and reported as approximate.
      out.push({ type: 'brightness', params: { amount: encodeTrack(fx.params.amount, (v) => (v - 1) * 100) } });
    } else if (fx.type === 'dropShadow') {
      const { dx, dy, blur, color } = fx.params;
      out.push({
        type: 'dropShadow',
        params: {
          color: color.rgb,
          alpha: color.a,
          direction: (Math.atan2(dx, -dy) * 180) / Math.PI,
          distance: Math.hypot(dx, dy),
          softness: blur,
        },
      });
    }
  }
  if (layer.skew) {
    // The Transform effect pivots on its OWN anchor point, which defaults to the
    // layer centre -- not the CSS transform-origin. Left alone it shears about
    // the wrong point and slides the layer sideways by tan(skew) x half the
    // height. Pass the transform-origin so both models pivot together.
    const anchor = layer.transform.anchorPoint.keys
      ? layer.transform.anchorPoint.keys[0].v
      : layer.transform.anchorPoint.static;
    out.push({
      type: 'skew',
      params: { skew: encodeTrack(layer.skew), anchor: [anchor[0], anchor[1]] },
    });
  }
  return out;
}
